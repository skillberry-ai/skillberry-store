"""Skill-side content the plugin maintains (design D8, D12, D15).

All of it is ordinary store data:

* each proxy tool's metadata lives in ``tool["extra"]["rossoctl"]``;
* the skill's required tools in ``skill["extra"]["rossoctl"]["required_tools"]``;
* ``rossoctl-tools.json`` is a ``file:rossoctl-tools.json`` snippet;
* the generated Tools section is appended to the skill's ``file:SKILL.md``
  instructions snippet, between markers so ``/refresh`` can replace it.
"""

import json
from typing import Any, Dict, List, Optional

TOOLS_JSON_PATH = "rossoctl-tools.json"
TOOLS_JSON_SCHEMA = "skillberry.ai/rossoctl-tools/v1"
PROXY_TAG = "rossoctl-proxy"
BEGIN = "<!-- rossoctl-tools:begin (generated by skillberry-store; edit the tools, then /refresh) -->"
END = "<!-- rossoctl-tools:end -->"


def meta(tool: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    """The plugin metadata of a proxy tool, or None for any other tool."""
    m = (tool.get("extra") or {}).get("rossoctl")
    return (
        m if isinstance(m, dict) and m.get("tool") and m.get("mcp_tool_name") else None
    )


def proxy_tools(tools: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    return [t for t in tools if meta(t)]


def required_tools(tools: List[Dict[str, Any]]) -> List[str]:
    """Sorted, de-duplicated rossoctl tool names behind ``tools`` (D8)."""
    return sorted({meta(t)["tool"] for t in proxy_tools(tools)})


def skill_required_tools(
    skill: Dict[str, Any], tools: List[Dict[str, Any]]
) -> List[str]:
    recorded = ((skill.get("extra") or {}).get("rossoctl") or {}).get("required_tools")
    if isinstance(recorded, list) and recorded:
        return sorted({str(t) for t in recorded})
    return required_tools(tools)


def tools_json(tools: List[Dict[str, Any]]) -> str:
    """``rossoctl-tools.json`` (D15)."""
    by_tool: Dict[str, Dict[str, Any]] = {}
    for t in proxy_tools(tools):
        m = meta(t)
        entry = by_tool.setdefault(
            m["tool"],
            {
                "tool": m["tool"],
                "port": m.get("port", 8000),
                "path": m.get("path", "/mcp"),
                "mcp_tools": [],
            },
        )
        if m.get("gateway_prefix"):
            entry["gateway_prefix"] = m["gateway_prefix"]
        entry["mcp_tools"].append(
            {
                "name": m["mcp_tool_name"],
                "store_tool": t["name"],
                "script": f"scripts/{t['name']}.py",
                "schema_sha256": m.get("input_schema_sha256", ""),
                "read_only": bool(m.get("read_only")),
            }
        )
    out = []
    for name in sorted(by_tool):
        by_tool[name]["mcp_tools"].sort(key=lambda x: x["name"])
        out.append(by_tool[name])
    return json.dumps({"schema": TOOLS_JSON_SCHEMA, "tools": out}, indent=2) + "\n"


def _arg_list(tool: Dict[str, Any]) -> str:
    params = tool.get("params") or {}
    req = set(params.get("required") or [])
    names = list((params.get("properties") or {}).keys())
    if not names:
        return "no arguments"
    return ", ".join(n if n in req else f"{n}?" for n in names)


def tools_section(tools: List[Dict[str, Any]]) -> str:
    """The generated Tools section (D12), wrapped in markers."""
    proxies = proxy_tools(tools)
    if not proxies:
        return ""
    lines = [
        BEGIN,
        "## Tools",
        "",
        "This skill uses the rossoctl tools "
        + ", ".join(f"`{n}`" for n in required_tools(proxies))
        + ". They are connected to you as **MCP tools**. Call them by the names below "
        "(with an MCP gateway, use the prefixed name). If you can run scripts, the same "
        "calls are available as `python3 scripts/<name>.py --<arg> …`.",
        "",
        "| MCP tool | Gateway name | Arguments (`?` = optional) | Effect |",
        "|---|---|---|---|",
    ]
    for t in sorted(proxies, key=lambda x: meta(x)["mcp_tool_name"]):
        m = meta(t)
        gw = (
            f"`{m['gateway_prefix']}{m['mcp_tool_name']}`"
            if m.get("gateway_prefix")
            else "—"
        )
        effect = "read-only" if m.get("read_only") else "**changes state**"
        lines.append(f"| `{m['mcp_tool_name']}` | {gw} | {_arg_list(t)} | {effect} |")
    lines += [
        "",
        "Before calling a tool that changes state, show the user what you will do and wait for an "
        "explicit confirmation. If a tool is not available or fails, say which one and do not make up "
        "a result.",
        END,
    ]
    return "\n".join(lines) + "\n"


def with_tools_section(instructions: str, section: str) -> str:
    """``instructions`` with the generated section replaced (or appended)."""
    text = instructions or ""
    if BEGIN in text and END in text:
        start = text.index(BEGIN)
        end = text.index(END) + len(END)
        text = (text[:start].rstrip("\n") + "\n\n" + text[end:].lstrip("\n")).strip(
            "\n"
        )
    if not section:
        return text + ("\n" if text else "")
    return (text.rstrip("\n") + "\n\n" if text.strip() else "") + section
